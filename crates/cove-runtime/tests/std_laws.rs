/// An object written in Rust with one field name written twice.
#[derive(Debug, Clone)]
struct Duplicate {
    /// The names, all different.
    names: Vec<String>,
    /// Which of them is written a second time.
    twice: usize,
    /// Where among the fields the second one goes: after `twice`.
    at: usize,
    /// Whether the second spelling is all `\u` escapes.
    escaped: bool,
    /// Whether there is whitespace between the tokens.
    spaced: bool,
    /// How many arrays the object is inside.
    depth: usize,
}

/// A JSON string spelling `name`: the escapes `render` would need, or every
/// UTF-16 unit as a `\u` escape.
fn json_string(name: &str, escaped: bool) -> String {
    let mut out = String::from('"');
    for c in name.chars() {
        if escaped {
            let mut units = [0u16; 2];
            for unit in c.encode_utf16(&mut units) {
                out.push_str(&format!("\\u{unit:04X}"));
            }
        } else {
            match c {
                '"' => out.push_str("\\\""),
                '\\' => out.push_str("\\\\"),
                c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
                c => out.push(c),
            }
        }
    }
    out.push('"');
    out
}

/// Values for the fields, none of them an object with a name twice.
const FIELD_VALUES: &[&str] = &[
    "null",
    "true",
    "false",
    "0",
    "-1.5e3",
    "\"x\"",
    "[]",
    "{}",
    "[1, {\"a\": 2, \"b\": [null]}]",
];

impl Duplicate {
    /// The object text, with the second occurrence or without it.
    fn text(&self, with_twice: bool) -> String {
        let gap = if self.spaced { " " } else { "" };
        let mut fields: Vec<String> = self
            .names
            .iter()
            .enumerate()
            .map(|(i, name)| {
                let value = FIELD_VALUES[i % FIELD_VALUES.len()];
                format!("{}{gap}:{gap}{value}", json_string(name, false))
            })
            .collect();
        if with_twice {
            let value = FIELD_VALUES[self.at % FIELD_VALUES.len()];
            let name = json_string(&self.names[self.twice], self.escaped);
            fields.insert(self.at, format!("{name}{gap}:{gap}{value}"));
        }
        let mut out = format!("{{{gap}{}{gap}}}", fields.join(&format!(",{gap}")));
        for _ in 0..self.depth {
            out = format!("[{gap}0,{gap}{out}{gap}]");
        }
        out
    }
}

fn duplicate() -> impl Strategy<Value = Duplicate> {
    (
        proptest::collection::btree_set(text(), 1..6),
        any::<proptest::sample::Index>(),
        any::<proptest::sample::Index>(),
        any::<bool>(),
        any::<bool>(),
        0usize..3,
    )
        .prop_map(|(names, twice, at, escaped, spaced, depth)| {
            let names: Vec<String> = names.into_iter().collect();
            let twice = twice.index(names.len());
            // After the first occurrence, anywhere up to the end.
            let at = twice + 1 + at.index(names.len() - twice);
            Duplicate {
                names,
                twice,
                at,
                escaped,
                spaced,
                depth,
            }
        })
}

