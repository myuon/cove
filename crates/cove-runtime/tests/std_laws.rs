/// Elements for `fromUtf8`: mostly bytes, often the ones UTF-8's table turns
/// on, and sometimes a value that is not a byte at all.
fn elements() -> BoxedStrategy<Vec<i64>> {
    let pivotal = proptest::sample::select(vec![
        0x00i64, 0x41, 0x7f, 0x80, 0x8f, 0x90, 0x9f, 0xa0, 0xbf, 0xc0, 0xc1, 0xc2, 0xdf, 0xe0,
        0xe1, 0xed, 0xee, 0xef, 0xf0, 0xf1, 0xf4, 0xf5, 0xff,
    ]);
    let not_a_byte = proptest::sample::select(vec![-1i64, 256, 1000, i64::MIN, i64::MAX]);
    let element = prop_oneof![
        8 => pivotal,
        8 => 0i64..256,
        1 => not_a_byte,
    ];
    // Well-formed text with one element replaced and the end cut anywhere,
    // which is where an ill-formed sequence is hardest to see.
    let damaged = (
        text(),
        any::<proptest::sample::Index>(),
        element.clone(),
        any::<proptest::sample::Index>(),
    )
        .prop_map(|(s, at, with, cut)| {
            let mut bytes: Vec<i64> = s.bytes().map(i64::from).collect();
            if !bytes.is_empty() {
                let at = at.index(bytes.len());
                bytes[at] = with;
                bytes.truncate(cut.index(bytes.len() + 1));
            }
            bytes
        });
    prop_oneof![
        2 => proptest::collection::vec(element, 0..16),
        1 => text().prop_map(|s| s.bytes().map(i64::from).collect()),
        2 => damaged,
    ]
    .boxed()
}

/// The bytes `elements` are, or `None` when one of them is not a byte.
fn as_bytes(elements: &[i64]) -> Option<Vec<u8>> {
    elements.iter().map(|&e| u8::try_from(e).ok()).collect()
}

/// ADR 0106: `fromUtf8` is Unicode's well-formedness, Table 3-7 and nothing
/// looser, and "an element outside `0` through `255`" is refused —
/// Rust's `str::from_utf8` is the same table, so it is the reference — and
/// "`fromUtf8(b)` is `Ok(text)` only where `text.toUtf8() == b`".
fn from_utf8_is_unicode_s_table(scale: u32) {
    property(
        "fromUtf8 is Table 3-7",
        scale,
        elements(),
        |laws, elements| {
            let arg = || vec![ints(elements.iter().copied())];
            laws.holds("fromUtf8KeepsTheBytes", arg())?;
            let got = laws.call("fromUtf8Of", arg())?;
            let want = as_bytes(elements).and_then(|bytes| String::from_utf8(bytes).ok());
            match (got.ok_payload(), want) {
                (Some([text]), Some(want)) if text.as_str() == Some(want.as_str()) => Ok(()),
                (None, None) if got.is_err() => Ok(()),
                (_, want) => Err(format!(
                    "fromUtf8 answered {got:?}, and Rust's from_utf8 {want:?}"
                )),
            }
        },
    );
}

