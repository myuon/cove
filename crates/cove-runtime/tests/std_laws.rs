/// The references are their ADRs' examples before they are anything else.
#[test]
fn the_references_answer_the_adrs_examples() {
    assert_eq!(percent_encoded("a b/é"), "a%20b%2F%C3%A9");
    assert_eq!(
        whatwg_form("a=1&&b=2&eq=a=b&tag&x=%2&y=%C3%A9+%41"),
        ["a", "1", "b", "2", "eq", "a=b", "tag", "", "x", "%2", "y", "é A"]
    );
    assert_eq!(whatwg_form("%C3"), ["\u{fffd}", ""]);
    assert_eq!(reference_decimal(7, 2), "07");
    assert_eq!(reference_decimal(42, 5), "00042");
    assert_eq!(reference_decimal(-5, 3), "-005");
    assert_eq!(reference_decimal(-5, 0), "-5");
    assert_eq!(reference_decimal(i64::MIN, 1), i64::MIN.to_string());
    assert_eq!(days_from_civil(1970, 1, 1), 0);
    assert_eq!(days_from_civil(1969, 12, 31), -1);
    assert_eq!(days_from_civil(2000, 3, 1), 11_017);
    assert_eq!(
        unescaped("it&#39;s &quot;5&quot; &lt; 6 &amp; 7 &gt; 4").as_deref(),
        Ok("it's \"5\" < 6 & 7 > 4")
    );
    assert!(unescaped("&nbsp;").is_err());
    let d = Duplicate {
        names: vec!["a".into(), "b".into()],
        twice: 0,
        at: 2,
        escaped: true,
        spaced: false,
        depth: 1,
    };
    assert_eq!(d.text(false), "[0,{\"a\":null,\"b\":true}]");
    assert_eq!(
        d.text(true),
        "[0,{\"a\":null,\"b\":true,\"\\u0061\":false}]"
    );
}

