/// Whether `byte` is RFC 3986's unreserved: `A-Z a-z 0-9 - . _ ~`.
fn unreserved(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'.' | b'_' | b'~')
}

/// RFC 3986 §2.1 percent-encoding of `text`'s UTF-8, every byte outside the
/// unreserved set as `%` and two uppercase digits.
fn percent_encoded(text: &str) -> String {
    text.bytes()
        .map(|byte| {
            if unreserved(byte) {
                char::from(byte).to_string()
            } else {
                format!("%{byte:02X}")
            }
        })
        .collect()
}

/// WHATWG URL Standard §5.1's urlencoded parser, over `body`'s UTF-8: the
/// pairs, flattened name then value.
fn whatwg_form(body: &str) -> Vec<String> {
    fn decoded(part: &str) -> String {
        let bytes = part.as_bytes();
        let mut out = Vec::new();
        let mut at = 0;
        while at < bytes.len() {
            let byte = bytes[at];
            let escape = (byte == b'%' && at + 2 < bytes.len())
                .then(|| {
                    let digits = std::str::from_utf8(&bytes[at + 1..at + 3]).ok()?;
                    if !digits.bytes().all(|b| b.is_ascii_hexdigit()) {
                        return None;
                    }
                    u8::from_str_radix(digits, 16).ok()
                })
                .flatten();
            match (byte, escape) {
                (_, Some(value)) => {
                    out.push(value);
                    at += 3;
                }
                (b'+', None) => {
                    out.push(b' ');
                    at += 1;
                }
                _ => {
                    out.push(byte);
                    at += 1;
                }
            }
        }
        String::from_utf8_lossy(&out).into_owned()
    }
    body.split('&')
        .filter(|piece| !piece.is_empty())
        .flat_map(|piece| {
            let (name, value) = piece.split_once('=').unwrap_or((piece, ""));
            [decoded(name), decoded(value)]
        })
        .collect()
}

