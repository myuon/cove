/// `String::from_utf8_lossy` and Python's `errors="replace"`" do, and "an
/// element outside `0` through `255` is not a byte, and is one U+FFFD of its
/// own" — which is what `0xFF`, a byte that starts nothing, gets, so the
/// reference reads such an element as `0xFF`.
fn from_utf8_lossy_is_rust_s(scale: u32) {
    property(
        "fromUtf8Lossy is Rust's",
        scale,
        elements(),
        |laws, elements| {
            let got = laws.text("fromUtf8LossyOf", vec![ints(elements.iter().copied())])?;
            let bytes: Vec<u8> = elements
                .iter()
                .map(|&e| u8::try_from(e).unwrap_or(0xff))
                .collect();
            let want = String::from_utf8_lossy(&bytes);
            (got == want)
                .then_some(())
                .ok_or_else(|| format!("fromUtf8Lossy answered {got:?}, Rust {want:?}"))
        },
    );
}

