//! The standard library's round-trip and law claims, run as properties on the
//! encoded VM and on the native tier.
//!
//! The ADRs that added `std.url`, `std.json`, `std.datetime`, `Int.toDecimal`,
//! `std.html` and the UTF-8 readers each claim something for *every* input —
//! "`percentDecode` reads every answer back to `text`", "any `String`
//! round-trips", "`toUnixMillis` is its inverse for all of those". Their tests
//! pinned examples. [Issue 679](https://github.com/myuon/cove/issues/679)
//! asked for the claims themselves, and this file is that.
//!
//! # Where the generator is and where the law is
//!
//! **The inputs are generated and shrunk in Rust, by `proptest`; the laws are
//! written in Cove.** Every law is an exported function of [`SOURCE`] that
//! takes the generated input as its arguments and answers a `String`: empty
//! when the law holds, and otherwise a sentence, written in Cove, saying what
//! broke. Where the law needs a reference Cove does not supply — Rust's own
//! `format!` for `toDecimal`, `String::from_utf8_lossy` for `fromUtf8Lossy`,
//! an entity decoder for `std.html` — the Cove function answers its value and
//! the comparison is made here, against a reference written independently of
//! the library, not ported from it.
//!
//! The alternative was a seeded random generator in Cove's `test fn`s. It
//! would have needed new library surface for a source of randomness and would
//! have had no shrinking, so a failure would have been a 24-character string
//! of arbitrary Unicode rather than the two characters that matter.
//!
//! **Every run is deterministic.** Each property's runner is built from a
//! ChaCha [`TestRng`] seeded from the property's name, with failure
//! persistence off, so the same inputs are asked on every machine and every
//! run, nothing is written beside the source, and the `proptest!` macro's
//! random seeding is not used. A failing property panics with the shrunk
//! input and what was wrong with it.
//!
//! # The tiers
//!
//! The fixture is checked, lowered and prepared once per property, and every
//! case is asked of the encoded VM and — where the tier can run, under
//! `all(feature = "template", target_arch = "x86_64", unix)` — of the native
//! tier, and the two answers have to be equal before the law is judged.
//!
//! The native half follows `int_bits.rs`. Each law has a caller the tier
//! refuses, generated by [`native_callers`], because the outermost frame is
//! always encoded; the case asserts that the run crossed into compiled code at
//! least once, so it cannot be the VM compared with itself. `Laws::new` holds
//! the tier's refusals to [`REFUSED_LAWS`] in both directions, and every
//! generated caller to being refused. As of issue 679 that list is empty:
//! the tier compiles every law here, and so every library function they call
//! that it compiles at all.
//!
//! The tree-walking interpreter is not asked. It is the reference the VM is
//! held to elsewhere, and its strings are Rust's.
//!
//! # UTF-8 on the way out
//!
//! Issue 679's last item is that every `String` is valid UTF-8 after any
//! standard-library operation (ADR 0046). On this side of the boundary that
//! is true by type: a `Value`'s string is an `Rc<str>`, and the VM's boundary
//! (`vm::boundary`) reads a heap string with `String::from_utf8` and answers a
//! `RuntimeError` rather than a `Value` when its bytes are not UTF-8. So every
//! law below that answers at all has passed that check on everything it
//! returns, on both tiers, and the UTF-8 properties at the end hold the
//! readers and the writer — `toUtf8`, `fromUtf8` and `fromUtf8Lossy`, ADR
//! 0106 — to Rust's own UTF-8 instead.
//!
//! # Cost
//!
//! [`CASES`] cases a property, on both tiers; `cargo t` runs that, 3.8s
//! on one core and 0.8s over the cores, of which 1.7s is the VM's and 1.3s the
//! native tier's (2026-10-25). `every_law_at_scale`, ignored, runs each with
//! [`SCALE`] times as many from other seeds, 20s on one core, and
//! `cargo ratchet` runs it.
//! Run with `--nocapture`, each property prints what each tier spent.

