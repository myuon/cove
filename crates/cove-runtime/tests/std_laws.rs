/// The text `said` decodes to, reading the five entities the escaper writes
/// and refusing anything else that starts with `&`.
fn unescaped(said: &str) -> Result<String, String> {
    const ENTITIES: [(&str, char); 5] = [
        ("&amp;", '&'),
        ("&lt;", '<'),
        ("&gt;", '>'),
        ("&quot;", '"'),
        ("&#39;", '\''),
    ];
    let mut out = String::new();
    let mut rest = said;
    while let Some(c) = rest.chars().next() {
        if c == '&' {
            let (entity, plain) = ENTITIES
                .iter()
                .find(|(entity, _)| rest.starts_with(entity))
                .ok_or_else(|| format!("a `&` starting no entity in {said:?}"))?;
            out.push(*plain);
            rest = &rest[entity.len()..];
        } else {
            out.push(c);
            rest = &rest[c.len_utf8()..];
        }
    }
    Ok(out)
}

/// `std.html` (ADR 0101, the escaping of ADR 0099 it kept): text in a hole of
/// an `html` literal, rendered, holds none of `& < > " '` raw except the `&`
/// of an entity the escaper wrote — checked in Cove — and decoding those
/// entities gives the text back — checked here.
///
/// Issue 679 asks that the rendered text "reparse to exactly one text node".
/// The standard library has no HTML parser, so that is this: an HTML parser
/// reads a run with no `<` as one text node, and its character references as
/// the characters they name.
fn html_holes_escape(scale: u32) {
    property("an html hole escapes", scale, text(), |laws, s| {
        let arg = || vec![Value::string(s.as_str())];
        laws.holds("htmlHoleLeavesNoRawCharacter", arg())?;
        let said = laws.text("htmlHole", arg())?;
        let back = unescaped(&said)?;
        (back == *s)
            .then_some(())
            .ok_or_else(|| format!("{said:?} decodes to {back:?}"))
    });
}

