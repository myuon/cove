/// A caller of every law that the native tier refuses, so that the law is
/// reached across the boundary: the outermost frame is always encoded.
///
/// One per `export fn` of [`SOURCE`], named `native` and the law's name, read
/// off the declaration. `Shared(…).lock` is what the tier refuses, as in
/// `int_bits.rs`. Every law calls the library, so none is a leaf, and
/// `cove_ir::lower::inline` does not expand a law into its caller.
fn native_callers() -> String {
    let mut out = String::new();
    for line in SOURCE.lines() {
        let Some(rest) = line.strip_prefix("export fn ") else {
            continue;
        };
        let (name, rest) = rest.split_once('(').expect("a law has parameters");
        let (params, rest) = rest.split_once(')').expect("a law's parameters close");
        let answer = rest
            .trim()
            .strip_prefix("->")
            .and_then(|r| r.strip_suffix('{'))
            .expect("a law answers something")
            .trim();
        let args: Vec<&str> = params
            .split(',')
            .filter_map(|p| p.split_once(':').map(|(n, _)| n.trim()))
            .collect();
        out.push_str(&format!(
            "\nexport fn {}({params}) -> {answer} {{\n  let nothing = Shared(0).lock(fn(v) {{ v }})\n  {name}({})\n}}\n",
            native_name(name),
            args.join(", "),
        ));
    }
    out
}

/// The refused caller of the law `name`.
fn native_name(name: &str) -> String {
    let mut chars = name.chars();
    let first = chars.next().expect("a law has a name");
    format!("native{}{}", first.to_ascii_uppercase(), chars.as_str())
}

/// [`SOURCE`] and its [`native_callers`], checked, with the standard library
/// attached.
fn checked() -> (Arc<SourceMap>, Arc<cove_sema::resolve::Program>) {
    let text = format!("{SOURCE}{}", native_callers());
    let mut sources = SourceMap::new();
    let path = PathBuf::from("m/main.cove");
    let file = sources.add(path.clone(), &text);
    let ast = cove_syntax::parse_file(&sources, file).expect("the fixture parses");
    let mut modules = BTreeMap::from([(
        MODULE.to_string(),
        Module {
            name: MODULE.to_string(),
            dir: PathBuf::from(MODULE),
            units: vec![Unit { file, path, ast }],
        },
    )]);
    for (name, module) in cove_sema::stdlib::attach(&mut sources).expect("stdlib parses") {
        modules.insert(name, module);
    }
    let package = Package {
        root: PathBuf::new(),
        config: Config::default(),
        modules,
    };
    match Compiler::new().compile(&package) {
        Ok(program) => (Arc::new(sources), Arc::new(program)),
        Err(items) => panic!(
            "the fixture checks:\n{}",
            items
                .iter()
                .map(|item| cove_diag::render(&sources, item))
                .collect::<Vec<_>>()
                .join("")
        ),
    }
}

/// The fixture, checked, lowered and prepared once — for the encoded VM, and
/// with its native tier compiled — and a runtime to run it in.
struct Laws {
    prepared: PreparedProgram,
    #[cfg(all(feature = "template", target_arch = "x86_64", unix))]
    native: PreparedProgram,
    hosts: Arc<HostRegistry>,
    runtime: Arc<Runtime>,
    /// Time spent on the VM and on the native tier, in that order.
    spent: RefCell<[Duration; 2]>,
}

impl Laws {
    fn new() -> Laws {
        let (sources, program) = checked();
        let lowered = Arc::new(
            cove_ir::lower(&program, &sources, &cove_sema::HostSchemas::new())
                .expect("the fixture lowers"),
        );
        let hosts = Arc::new(HostRegistry::new(Grants::new(Vec::<&str>::new())));
        let runtime = Arc::new(Runtime::new(program, sources, Arc::clone(&hosts)));
        let prepared = PreparedProgram::new(Arc::clone(&lowered));
        #[cfg(all(feature = "template", target_arch = "x86_64", unix))]
        let native = {
            let native = PreparedProgram::new(lowered)
                .with_native()
                .expect("this host compiles");
            let refused: Vec<(String, String)> = native
                .native()
                .expect("compiled")
                .refusals()
                .iter()
                .filter_map(|row| {
                    let law = row.name.strip_prefix("m.")?;
                    (!law.starts_with("native")).then(|| (law.to_string(), row.reason.clone()))
                })
                .collect();
            let names: Vec<&str> = refused.iter().map(|(law, _)| law.as_str()).collect();
            assert_eq!(
                names, REFUSED_LAWS,
                "the laws the native tier refuses are not the ones listed: {refused:#?}"
            );
            for name in SOURCE.lines().filter_map(|l| l.strip_prefix("export fn ")) {
                let caller = native_name(&name[..name.find('(').expect("a law")]);
                assert!(
                    native
                        .native()
                        .expect("compiled")
                        .refusals()
                        .iter()
                        .any(|row| row.name == format!("m.{caller}")),
                    "`{caller}` is meant to be refused, and the tier took it"
                );
            }
            native
        };
        Laws {
            prepared,
            #[cfg(all(feature = "template", target_arch = "x86_64", unix))]
            native,
            hosts,
            runtime,
            spent: RefCell::new([Duration::ZERO; 2]),
        }
    }

    /// `name` called with `args` on the encoded VM, or the sentence the run
    /// stopped with — and, where the native tier is built, the same call
    /// through `name`'s refused caller, which has to have crossed into
    /// compiled code and to have answered the same.
    ///
    /// A string that was not UTF-8 is a stop here: the boundary refuses it.
    fn call(&self, name: &str, args: Vec<Value>) -> Result<Value, String> {
        #[cfg(all(feature = "template", target_arch = "x86_64", unix))]
        let native_args = args.clone();
        let started = Instant::now();
        let answer = Vm::with_prepared(&self.runtime, &self.hosts, &self.prepared)
            .invoke(MODULE, name, args)
            .map_err(|error| error.message);
        self.spent.borrow_mut()[0] += started.elapsed();
        #[cfg(all(feature = "template", target_arch = "x86_64", unix))]
        {
            let started = Instant::now();
            let caller = native_name(name);
            let mut vm = OwnedVm::new(
                Arc::clone(&self.runtime),
                Arc::clone(&self.hosts),
                self.native.clone(),
            );
            let native = vm
                .invoke(MODULE, &caller, native_args)
                .map_err(|error| error.message);
            self.spent.borrow_mut()[1] += started.elapsed();
            if vm.tiers().vm_to_native == 0 {
                return Err(format!(
                    "`{caller}` never crossed into compiled code: {:?}",
                    vm.tiers()
                ));
            }
            let same = match (&answer, &native) {
                (Ok(vm), Ok(native)) => vm.eq_value(native) == Ok(true),
                (Err(vm), Err(native)) => vm == native,
                _ => false,
            };
            if !same {
                return Err(format!(
                    "`{name}` answered {answer:?} on the VM and {native:?} on the native tier"
                ));
            }
        }
        answer.map_err(|message| format!("`{name}` stopped: {message}"))
    }

    /// `name`'s `String` answer.
    fn text(&self, name: &str, args: Vec<Value>) -> Result<String, String> {
        let value = self.call(name, args)?;
        value
            .as_str()
            .map(str::to_string)
            .ok_or_else(|| format!("`{name}` answered {value:?}, not a `String`"))
    }

    /// Holds the law `name`: its answer is empty, or it is the violation.
    fn holds(&self, name: &str, args: Vec<Value>) -> Result<(), String> {
        let said = self.text(name, args)?;
        if said.is_empty() {
            Ok(())
        } else {
            Err(format!("`{name}`: {said}"))
        }
    }
}

/// The laws the native tier refuses to compile, which has to be what the
/// tier's own refusal list says: these would run encoded even under their
/// refused caller, and only their callees in the library are compiled.
#[cfg(all(feature = "template", target_arch = "x86_64", unix))]
const REFUSED_LAWS: &[&str] = &[];

/// Cases per property in `cargo t`.
const CASES: u32 = 1024;

/// How many times [`CASES`] the ignored run asks.
const SCALE: u32 = 10;

/// A ChaCha seed from `name` and `scale`, FNV-1a spread over 32 bytes, so that
/// each property asks its own inputs and the scaled run asks different ones.
fn seed(name: &str, scale: u32) -> [u8; 32] {
    let mut out = [0u8; 32];
    for (lane, chunk) in out.chunks_mut(8).enumerate() {
        let mut hash: u64 = 0xcbf2_9ce4_8422_2325 ^ lane as u64;
        for byte in name.bytes().chain(scale.to_le_bytes()) {
            hash ^= u64::from(byte);
            hash = hash.wrapping_mul(0x0100_0000_01b3);
        }
        chunk.copy_from_slice(&hash.to_le_bytes());
    }
    out
}

/// Runs `law` over `strategy`, `CASES * scale` cases from a seed of
/// `name`'s, and panics with the shrunk input if a case fails.
///
/// What each tier spent is written to standard error, which `--nocapture`
/// shows.
fn property<S>(
    name: &str,
    scale: u32,
    strategy: S,
    law: impl Fn(&Laws, &S::Value) -> Result<(), String>,
) where
    S: Strategy,
    S::Value: fmt::Debug,
{
    let laws = Laws::new();
    let config = RunConfig {
        cases: CASES * scale,
        failure_persistence: None,
        source_file: None,
        rng_algorithm: RngAlgorithm::ChaCha,
        ..RunConfig::default()
    };
    let rng = TestRng::from_seed(RngAlgorithm::ChaCha, &seed(name, scale));
    let mut runner = TestRunner::new_with_rng(config, rng);
    let outcome = runner.run(&strategy, |input| {
        law(&laws, &input).map_err(TestCaseError::fail)
    });
    let [vm, native] = *laws.spent.borrow();
    eprintln!("{name}: {vm:?} on the VM, {native:?} on the native tier");
    match outcome {
        Ok(()) => {}
        Err(TestError::Fail(why, input)) => {
            panic!("{name} fails.\n{why}\nshrunk input: {input:#?}")
        }
        Err(TestError::Abort(why)) => panic!("{name} was abandoned: {why}"),
    }
}

